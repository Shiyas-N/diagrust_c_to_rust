pub struct FunctionTranslator;

impl FunctionTranslator {
    pub fn emit(func: &IrFunction) -> anyhow::Result<String> {
        let mut out = String::new();

        if func.is_main {
            out.push_str("fn main() {\n");
        } else {
            out.push_str("pub fn ");
            out.push_str(&func.name);
            out.push('(');
            for (i, param) in func.parameters.iter().enumerate() {
                if i > 0 { out.push_str(", "); }
                // Slice params (&mut [T]) don't need extra `mut` prefix on the binding
                if param.is_mutable && !param.rust_type.starts_with("&mut") {
                    out.push_str("mut ");
                }
                out.push_str(&param.name);
                out.push_str(": ");
                out.push_str(&param.rust_type);
            }
            out.push(')');
            if func.rust_return_type != "()" {
                out.push_str(" -> ");
                out.push_str(&func.rust_return_type);
            }
            out.push_str(" {\n");
        }

        for stmt in &func.body {
            out.push_str(&Self::emit_stmt(stmt, 1, func.requires_unsafe)?);
        }

        out.push('}');
        Ok(out)
    }

    fn emit_stmt(stmt: &IrStatement, depth: usize, unsafe_ctx: bool) -> anyhow::Result<String> {
        let ind  = "    ".repeat(depth);
        let ind1 = "    ".repeat(depth + 1);
        Ok(match stmt {
            IrStatement::LetBinding { name, rust_type, init, is_mutable } => {
                let mut_kw = if *is_mutable { "mut " } else { "" };
                let rhs = if let Some(expr) = init {
                    format!(" = {}", ExprEmitter::emit(expr)?)
                } else if rust_type.starts_with('[') {
                    if let Some(sz) = extract_array_size(rust_type) {
                        let elem = extract_array_elem_type(rust_type);
                        let zero = array_default_value(&elem);
                        format!(" = [{}; {}]", zero, sz)
                    } else { " = Vec::new()".to_string() }
                } else if rust_type.starts_with("Vec<") {
                    " = Vec::new()".to_string()
                } else { String::new() };
                if rhs.is_empty() {
                    format!("{}let {}{}: {};\n", ind, mut_kw, name, rust_type)
                } else {
                    format!("{}let {}{}: {}{};\n", ind, mut_kw, name, rust_type, rhs)
                }
            }

            IrStatement::Assign { target, value } =>
                format!("{}{} = {};\n", ind, target, ExprEmitter::emit(value)?),

            IrStatement::IndexAssign { array, index, value } =>
                format!("{}{}[{}] = {};\n", ind, array, ExprEmitter::emit(index)?, ExprEmitter::emit(value)?),

            IrStatement::FieldAssign { object, field, value } =>
                format!("{}{}.{} = {};\n", ind, object, field, ExprEmitter::emit(value)?),

            IrStatement::SwapElements { array, i, j } =>
                format!("{}{}.swap({}, {});\n", ind, array, ExprEmitter::emit(i)?, ExprEmitter::emit(j)?),

            IrStatement::Return(Some(e)) =>
                format!("{}return {};\n", ind, ExprEmitter::emit(e)?),
            IrStatement::Return(None) => format!("{}return;\n", ind),

            IrStatement::Break    => format!("{}break;\n",    ind),
            IrStatement::Continue => format!("{}continue;\n", ind),

            IrStatement::Expr(e) => {
                match e {
                    IrExpr::PrintLn  { fmt, args } => emit_print_macro(&ind, "println", fmt, args)?,
                    IrExpr::Print    { fmt, args } => {
                        let s = emit_print_macro_str("print", fmt, args)?;
                        format!("{}{};\n{}io::stdout().flush().unwrap();\n", ind, s, ind)
                    }
                    IrExpr::EPrintLn { fmt, args } => emit_print_macro(&ind, "eprintln", fmt, args)?,
                    IrExpr::ReadLine { var }        => emit_read_line(&ind, var),
                    IrExpr::Exit(code)              =>
                        format!("{}std::process::exit({});\n", ind, ExprEmitter::emit(code)?),
                    other => format!("{}{};", ind, ExprEmitter::emit(other)?),
                }
            }

            IrStatement::Drop(var) => format!("{}drop({});\n", ind, var),

            IrStatement::If { condition, then_block, else_block } => {
                let mut s = format!("{}if {} {{\n", ind, ExprEmitter::emit(condition)?);
                for st in then_block { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                s.push_str(&format!("{}}}", ind));
                if let Some(eb) = else_block {
                    s.push_str(" else {\n");
                    for st in eb { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                    s.push_str(&format!("{}}}", ind));
                }
                s.push('\n');
                s
            }

            IrStatement::While { condition, body } => {
                let mut s = format!("{}while {} {{\n", ind, ExprEmitter::emit(condition)?);
                for st in body { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                s.push_str(&format!("{}}}\n", ind));
                s
            }

            IrStatement::While2 { init, condition, increment, body } => {
                let mut s = Self::emit_stmt(init, depth, unsafe_ctx)?;
                s.push_str(&format!("{}while {} {{\n", ind, ExprEmitter::emit(condition)?));
                for st in body { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                let incr = ExprEmitter::emit(increment)?;
                if !incr.is_empty() && incr != "()" {
                    s.push_str(&format!("{}{};  \n", ind1, incr));
                }
                s.push_str(&format!("{}}}\n", ind));
                s
            }

            IrStatement::UnsafeBlock(stmts) => {
                // If we're already inside an unsafe context, skip the wrapper
                if unsafe_ctx {
                    let mut s = String::new();
                    for st in stmts { s.push_str(&Self::emit_stmt(st, depth, true)?); }
                    s
                } else {
                    let mut s = format!("{}unsafe {{\n", ind);
                    for st in stmts { s.push_str(&Self::emit_stmt(st, depth + 1, true)?); }
                    s.push_str(&format!("{}}}\n", ind));
                    s
                }
            }
        })
    }
}

// ── print macro helpers ──────────────────────────────────────────────────────

fn emit_print_macro(ind: &str, mac: &str, fmt: &str, args: &[IrExpr]) -> anyhow::Result<String> {
    Ok(format!("{}{};\n", ind, emit_print_macro_str(mac, fmt, args)?))
}

fn emit_print_macro_str(mac: &str, fmt: &str, args: &[IrExpr]) -> anyhow::Result<String> {
    if args.is_empty() {
        Ok(format!("{}!(\"{}\")", mac, fmt))
    } else {
        let args_str = args.iter()
            .map(ExprEmitter::emit)
            .collect::<anyhow::Result<Vec<_>>>()?
            .join(", ");
        Ok(format!("{}!(\"{}\", {})", mac, fmt, args_str))
    }
}

fn emit_read_line(ind: &str, var: &str) -> String {
    format!(
        "{ind}let mut _input_buf = String::new();\n\
         {ind}io::stdin().read_line(&mut _input_buf).expect(\"Failed to read input\");\n\
         {ind}let {var} = _input_buf.trim().parse().unwrap_or_default();\n",
        ind = ind, var = var
    )
}

fn extract_array_size(rust_type: &str) -> Option<usize> {
    let semi = rust_type.find(';')?;
    let end  = rust_type.rfind(']')?;
    rust_type[semi + 1..end].trim().parse().ok()
}

// ─────────────────────────────────────────────────────────────────────────────
// Expression Emitter
// ─────────────────────────────────────────────────────────────────────────────

pub struct ExprEmitter;

impl ExprEmitter {
    pub fn emit(expr: &IrExpr) -> anyhow::Result<String> {
        Ok(match expr {
            IrExpr::IntLit(n)    => n.to_string(),
            IrExpr::FloatLit(f)  => {
                if f.fract() == 0.0 { format!("{:.1}", f) } else { f.to_string() }
            }
            IrExpr::BoolLit(b)   => b.to_string(),
            IrExpr::StringLit(s) => format!("\"{}\"", s),
            IrExpr::CharLit(c)   => format!("b'{}'", c),
            IrExpr::Null | IrExpr::NullMut => "std::ptr::null_mut()".to_string(),
            IrExpr::OptionNone   => "None".to_string(),
            IrExpr::OptionSome(i) => format!("Some({})", Self::emit(i)?),
            IrExpr::Var(name)    => name.clone(),

            IrExpr::BinOp { left, op, right } =>
                format!("{} {} {}", Self::emit(left)?, binop_str(op), Self::emit(right)?),

            IrExpr::UnaryOp { op, operand } =>
                format!("{}{}", unaryop_str(op), Self::emit(operand)?),

            IrExpr::Call { function, args } => {
                if function == "__to_vec__" {
                    if let Some(arr) = args.first() {
                        return Ok(format!("{}.to_vec()", Self::emit(arr)?));
                    }
                }
                let args_str = args.iter()
                    .map(Self::emit)
                    .collect::<anyhow::Result<Vec<_>>>()?
                    .join(", ");
                format!("{}({})", function, args_str)
            }

            IrExpr::ArrayAccess { array, index } =>
                format!("{}[{}]", Self::emit(array)?, Self::emit(index)?),

            IrExpr::ArrayLiteral(elems) => {
                let s = elems.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                format!("[{}]", s)
            }

            IrExpr::Cast { to_type, expr } =>
                format!("({}) as {}", Self::emit(expr)?, to_type),

            IrExpr::AsUsize(inner) =>
                format!("({}) as usize", Self::emit(inner)?),

            IrExpr::BoxNew(inner)     => format!("Box::new({})", Self::emit(inner)?),
            IrExpr::RcNew(inner)      => format!("Rc::new({})", Self::emit(inner)?),
            IrExpr::RefCellNew(inner) => format!("RefCell::new({})", Self::emit(inner)?),

            IrExpr::VecNew { elem_type, len } => {
                let zero = primitive_default(elem_type);
                format!("vec![{}; {}]", zero, Self::emit(len)?)
            }

            IrExpr::StructDefault(name) => format!("{}::default()", name),

            IrExpr::FieldAccess { object, field } =>
                format!("{}.{}", Self::emit(object)?, field),

            IrExpr::StructLiteral { struct_type, fields } => {
                let mut s = format!("{} {{ ", struct_type);
                for (i, (fname, fexpr)) in fields.iter().enumerate() {
                    if i > 0 { s.push_str(", "); }
                    s.push_str(&format!("{}: {}", fname, Self::emit(fexpr)?));
                }
                s.push_str(" }");
                s
            }

            IrExpr::Deref(inner)  => format!("(*{})", Self::emit(inner)?),
            IrExpr::Ref(inner)    => format!("(&{})", Self::emit(inner)?),
            IrExpr::RefMut(inner) => format!("(&mut {})", Self::emit(inner)?),
            IrExpr::Clone(inner)  => format!("{}.clone()", Self::emit(inner)?),

            IrExpr::PrintLn { fmt, args } => {
                if args.is_empty() { format!("println!(\"{}\")", fmt) }
                else {
                    let a = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                    format!("println!(\"{}\", {})", fmt, a)
                }
            }
            IrExpr::Print { fmt, args } => {
                if args.is_empty() { format!("print!(\"{}\")", fmt) }
                else {
                    let a = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                    format!("print!(\"{}\", {})", fmt, a)
                }
            }
            IrExpr::EPrintLn { fmt, args } => {
                if args.is_empty() { format!("eprintln!(\"{}\")", fmt) }
                else {
                    let a = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                    format!("eprintln!(\"{}\", {})", fmt, a)
                }
            }
            IrExpr::ReadLine { var } => format!("/* read -> {} */", var),
            IrExpr::Exit(code) => format!("std::process::exit({})", Self::emit(code)?),
        })
    }
}

fn primitive_default(t: &str) -> &str {
    match t {
        "bool" => "false",
        t if t.starts_with('f') => "0.0",
        _ => "0",
    }
}

fn binop_str(op: &BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",  BinOp::Sub => "-", BinOp::Mul => "*",
        BinOp::Div => "/",  BinOp::Mod => "%",
        BinOp::Equal => "==", BinOp::NotEqual => "!=",
        BinOp::Less => "<",  BinOp::LessEq => "<=",
        BinOp::Greater => ">", BinOp::GreaterEq => ">=",
        BinOp::And => "&&", BinOp::Or => "||",
        BinOp::Assign => "=",
        BinOp::BitAnd => "&", BinOp::BitOr => "|", BinOp::BitXor => "^",
        BinOp::Shl => "<<", BinOp::Shr => ">>",
    }
}

fn unaryop_str(op: &UnaryOp) -> &'static str {
    match op {
        UnaryOp::Neg    => "-",
        UnaryOp::Not    => "!",
        UnaryOp::Deref  => "*",
        UnaryOp::AddrOf => "&",
        UnaryOp::BitNot => "!",
    }
}
