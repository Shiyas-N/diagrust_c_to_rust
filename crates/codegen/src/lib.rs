//! # Rust Code Generation Module

use ir::*;
use ast_input::{BinOp, UnaryOp};
use std::collections::HashSet;

pub struct CodeAssembler;

impl CodeAssembler {
    pub fn generate(program: &IrProgram) -> anyhow::Result<String> {
        let mut out = String::new();

        out.push_str("// Auto-generated by DIAGRUST\n");
        out.push_str("// Compiler-in-the-Loop C to Rust Transpiler\n\n");

        let mut uses = program.required_uses.clone();
        // std::io::{self, Write} is added by the IR builder only when print! (with flush)
        // is actually used. We do NOT add it unconditionally here anymore.
        uses.sort();
        uses.dedup();
        for u in &uses {
            out.push_str(&format!("use {};\n", u));
        }
        if !uses.is_empty() { out.push('\n'); }

        // Collect struct names for Copy derive resolution.
        // A struct whose fields are all Copy (primitives or other Copy structs) is Copy.
        let struct_names: HashSet<String> = program.structs.iter().map(|s| s.name.clone()).collect();
        let mut copy_structs: HashSet<String> = HashSet::new();

        // Multi-pass: resolve Copy transitively (struct A has Copy fields → A is Copy;
        //             struct B has field of type A → B is Copy too).
        loop {
            let mut changed = false;
            for s in &program.structs {
                if copy_structs.contains(&s.name) { continue; }
                let all_copy = s.fields.iter().all(|f| {
                    is_copy_type(&f.rust_type) || copy_structs.contains(&f.rust_type)
                });
                if all_copy {
                    copy_structs.insert(s.name.clone());
                    changed = true;
                }
            }
            if !changed { break; }
        }

        // Struct definitions
        for s in &program.structs {
            let all_copy = copy_structs.contains(&s.name);
            let needs_manual = s.fields.iter().any(|f| needs_manual_default_impl(&f.rust_type));
            if all_copy && !needs_manual {
                out.push_str("#[derive(Debug, Clone, Copy, Default)]\n");
            } else if !needs_manual {
                out.push_str("#[derive(Debug, Clone, Default)]\n");
            } else if all_copy {
                out.push_str("#[derive(Debug, Clone, Copy)]\n");
            } else {
                out.push_str("#[derive(Debug, Clone)]\n");
            }
            out.push_str(&format!("pub struct {} {{\n", s.name));
            for field in &s.fields {
                out.push_str(&format!("    pub {}: {},\n", field.name, field.rust_type));
            }
            out.push_str("}\n");
            if needs_manual {
                out.push_str(&format!("impl Default for {} {{\n    fn default() -> Self {{\n        Self {{\n", s.name));
                for field in &s.fields {
                    let def_val = field_default_value(&field.rust_type, &field.name);
                    out.push_str(&format!("            {},\n", def_val));
                }
                out.push_str("        }\n    }\n}\n");
            }
            out.push('\n');
        }

        // Global variables / constants — collect names for function-body rewriting
        let mut global_names: HashSet<String> = HashSet::new();
        for gv in &program.global_vars {
            global_names.insert(gv.name.clone());
            if gv.is_const {
                if let Some(init) = &gv.init {
                    out.push_str(&format!("pub const {}: {} = {};\n",
                        gv.name.to_uppercase(), gv.rust_type, ExprEmitter::emit(init)?));
                }
            } else {
                let init_str = static_init_for_type(&gv.rust_type, gv.init.as_ref());
                out.push_str(&format!(
                    "// Global variable — use unsafe {{ }} to access\nstatic mut {}: {} = {};\n",
                    gv.name.to_uppercase(), gv.rust_type, init_str
                ));
            }
        }
        if !program.global_vars.is_empty() { out.push('\n'); }

        // Functions — rewrite global variable references and wrap in unsafe
        for func in &program.functions {
            let mut fn_code = FunctionTranslator::emit(func)?;
            // Rewrite global variable references: lowercase → UPPERCASE
            let mut uses_globals = false;
            for gname in &global_names {
                let upper = gname.to_uppercase();
                if fn_code.contains(gname.as_str()) {
                    fn_code = fn_code.replace(gname, &upper);
                    uses_globals = true;
                }
            }
            // If this function uses globals, wrap the ENTIRE body in one unsafe block
            if uses_globals {
                fn_code = wrap_body_in_unsafe(&fn_code);
            }
            out.push_str(&fn_code);
            out.push_str("\n\n");
        }

        Ok(out)
    }
}

fn is_copy_type(t: &str) -> bool {
    matches!(t, "i8"|"i16"|"i32"|"i64"|"i128"|"isize"
               |"u8"|"u16"|"u32"|"u64"|"u128"|"usize"
               |"f32"|"f64"|"bool"|"char"|"()")
    || t.starts_with('*')
    || (t.starts_with('[') && t.contains(';'))
}

fn needs_manual_default_impl(t: &str) -> bool {
    if !t.starts_with('[') { return false; }
    if let Some(sz) = extract_array_size(t) { sz > 32 } else { false }
}

fn extract_array_elem_type(t: &str) -> String {
    if let (Some(start), Some(semi)) = (t.find('['), t.find(';')) {
        t[start + 1..semi].trim().to_string()
    } else { "i32".to_string() }
}

fn array_default_value(elem_type: &str) -> String {
    match elem_type {
        "f32" | "f64" => "0.0".to_string(),
        "bool" => "false".to_string(),
        t if t.starts_with('*') => "std::ptr::null_mut()".to_string(),
        "i8"|"i16"|"i32"|"i64"|"i128"|"isize"
        |"u8"|"u16"|"u32"|"u64"|"u128"|"usize" => "0".to_string(),
        other => format!("{} {{ ..Default::default() }}", other),
    }
}

fn static_init_for_type(rust_type: &str, _init: Option<&IrExpr>) -> String {
    if rust_type.starts_with('[') {
        if let Some(sz) = extract_array_size(rust_type) {
            let elem = extract_array_elem_type(rust_type);
            if elem.chars().next().map(|c| c.is_uppercase()).unwrap_or(false) {
                return "unsafe { std::mem::zeroed() }".to_string();
            }
            let zero = match elem.as_str() {
                "f32" | "f64" => "0.0", "bool" => "false", _ => "0",
            };
            return format!("[{}; {}]", zero, sz);
        }
    }
    match rust_type {
        "i32"|"u32"|"i64"|"u64"|"i16"|"u16"|"i8"|"u8"|"usize"|"isize" => "0".to_string(),
        "f32"|"f64" => "0.0".to_string(),
        "bool" => "false".to_string(),
        _ => "0".to_string(),
    }
}

fn field_default_value(rust_type: &str, field_name: &str) -> String {
    if rust_type.starts_with('[') {
        if let Some(sz) = extract_array_size(rust_type) {
            let elem = extract_array_elem_type(rust_type);
            let zero = match elem.as_str() { "f32" | "f64" => "0.0", "bool" => "false", _ => "0" };
            return format!("{}: [{}; {}]", field_name, zero, sz);
        }
    }
    let def = match rust_type {
        "f32" | "f64" => "0.0".to_string(),
        "bool" => "false".to_string(),
        t if t.starts_with('*') => "std::ptr::null_mut()".to_string(),
        _ if rust_type.chars().next().map(|c| c.is_uppercase()).unwrap_or(false) =>
            format!("{}::default()", rust_type),
        _ => "0".to_string(),
    };
    format!("{}: {}", field_name, def)
}

// ─────────────────────────────────────────────────────────────────────────────
// Function Translator
// ─────────────────────────────────────────────────────────────────────────────

pub struct FunctionTranslator;

impl FunctionTranslator {
    pub fn emit(func: &IrFunction) -> anyhow::Result<String> {
        let mut out = String::new();

        if func.is_main {
            out.push_str("fn main() {\n");
        } else {
            // ── Lifetime annotation analysis ───────────────────────────────────
            // If the function returns a reference type (&T, &[T], &mut T) and
            // has reference parameters, we must add lifetime annotations so that
            // Rust can verify borrow validity.  We use a single lifetime `'a`
            // assigned to all reference params and the return type.
            let ret_is_ref = func.rust_return_type.starts_with('&');
            let ref_params: Vec<usize> = func.parameters.iter().enumerate()
                .filter(|(_, p)| p.rust_type.starts_with('&'))
                .map(|(i, _)| i)
                .collect();
            let needs_lifetime = ret_is_ref && !ref_params.is_empty();

            out.push_str("pub fn ");
            out.push_str(&func.name);
            if needs_lifetime { out.push_str("<'a>"); }
            out.push('(');
            for (i, param) in func.parameters.iter().enumerate() {
                if i > 0 { out.push_str(", "); }
                if param.is_mutable && !param.rust_type.starts_with("&mut") {
                    out.push_str("mut ");
                }
                out.push_str(&param.name);
                out.push_str(": ");
                // Add 'a lifetime to reference parameters
                let ty = if needs_lifetime && ref_params.contains(&i) {
                    annotate_lifetime(&param.rust_type, "'a")
                } else {
                    param.rust_type.clone()
                };
                out.push_str(&ty);
            }
            out.push(')');
            if func.rust_return_type != "()" {
                out.push_str(" -> ");
                let ret_ty = if needs_lifetime {
                    annotate_lifetime(&func.rust_return_type, "'a")
                } else {
                    func.rust_return_type.clone()
                };
                out.push_str(&ret_ty);
            }
            out.push_str(" {\n");
        }

        // The IR's wrap_global_accesses wraps the entire function body in a
        // single UnsafeBlock when globals are accessed.  The requires_unsafe
        // flag is set in that case.  We emit that block directly (which adds
        // the `unsafe { }` wrapper) rather than adding a second one here.
        for stmt in &func.body {
            out.push_str(&Self::emit_stmt(stmt, 1, false)?);
        }

        out.push('}');
        Ok(out)
    }

    fn emit_stmt(stmt: &IrStatement, depth: usize, unsafe_ctx: bool) -> anyhow::Result<String> {
        let ind  = "    ".repeat(depth);
        let ind1 = "    ".repeat(depth + 1);
        Ok(match stmt {
            IrStatement::LetBinding { name, rust_type, init, is_mutable } => {
                let mut_kw = if *is_mutable { "mut " } else { "" };
                // For heap-allocated inits, derive the correct Rust type from the expression
                // rather than trusting the declared (possibly stale *mut T) type.
                let effective_type: std::borrow::Cow<str> = match init {
                    Some(IrExpr::BoxNew(inner)) => {
                        // Box<T> — infer T from inner expression or use declared inner
                        let inner_ty = if rust_type.starts_with("Box<") {
                            rust_type.as_str().to_owned()
                        } else if rust_type.starts_with("*mut ") {
                            format!("Box<{}>", &rust_type["*mut ".len()..])
                        } else {
                            rust_type.clone()
                        };
                        std::borrow::Cow::Owned(inner_ty)
                    }
                    Some(IrExpr::VecNew { elem_type, .. }) => {
                        if elem_type == "u8" || elem_type == "char" {
                            std::borrow::Cow::Borrowed("String")
                        } else {
                            std::borrow::Cow::Owned(format!("Vec<{}>", elem_type))
                        }
                    }
                    _ => std::borrow::Cow::Borrowed(rust_type.as_str()),
                };
                let rust_type = effective_type.as_ref();
                let rhs = if let Some(expr) = init {
                    let emitted = ExprEmitter::emit(expr)?;
                    // If the init expression is a comparison but the target type is
                    // an integer (C's `int result = a > b;`), wrap with
                    // `if expr { 1 } else { 0 }`.
                    let is_int_type = matches!(rust_type,
                        "i8"|"i16"|"i32"|"i64"|"u8"|"u16"|"u32"|"u64"|"isize"|"usize");
                    let is_comparison = matches!(expr,
                        IrExpr::BinOp { op: BinOp::Greater | BinOp::Less |
                            BinOp::GreaterEq | BinOp::LessEq |
                            BinOp::Equal | BinOp::NotEqual, .. });
                    if is_int_type && is_comparison {
                        format!(" = if {} {{ 1 }} else {{ 0 }}", emitted)
                    } else if rust_type == "String" && matches!(expr, IrExpr::StringLit(_)) {
                        // `"Hello"` is &str; coerce to String for String-typed variables
                        format!(" = {}.to_string()", emitted)
                    } else if rust_type == "String" && emitted == "String::new()" {
                        " = String::new()".to_string()
                    } else {
                        format!(" = {}", emitted)
                    }
                } else if rust_type.starts_with('[') {
                    if let Some(sz) = extract_array_size(rust_type) {
                        let elem = extract_array_elem_type(rust_type);
                        let zero = array_default_value(&elem);
                        format!(" = [{}; {}]", zero, sz)
                    } else { " = Vec::new()".to_string() }
                } else if rust_type.starts_with("Vec<") {
                    " = Vec::new()".to_string()
                } else if rust_type == "String" {
                    " = String::new()".to_string()
                } else if rust_type.starts_with("Box<") {
                    // Box vars always need init from patch_malloc_vars; bare decl is unusual
                    String::new()
                } else { String::new() };
                if rhs.is_empty() {
                    format!("{}let {}{}: {};\n", ind, mut_kw, name, rust_type)
                } else {
                    format!("{}let {}{}: {}{};\n", ind, mut_kw, name, rust_type, rhs)
                }
            }

            IrStatement::Assign { target, value } => {
                let rhs = ExprEmitter::emit(value)?;
                // Strip any `as *mut T` or `as String` cast wrapping Vec/Box allocations
                // that may remain if type upgrade didn't fully propagate.
                format!("{}{} = {};\n", ind, target, rhs)
            }

            IrStatement::IndexAssign { array, index, value } =>
                format!("{}{}[{}] = {};\n", ind, array, ExprEmitter::emit(index)?, ExprEmitter::emit(value)?),

            IrStatement::FieldAssign { object, field, value } =>
                format!("{}{}.{} = {};\n", ind, object, field, ExprEmitter::emit(value)?),

            IrStatement::SwapElements { array, i, j } =>
                format!("{}{}.swap({}, {});\n", ind, array, ExprEmitter::emit(i)?, ExprEmitter::emit(j)?),

            IrStatement::Return(Some(e)) =>
                format!("{}return {};\n", ind, ExprEmitter::emit(e)?),
            IrStatement::Return(None) => format!("{}return;\n", ind),

            IrStatement::Break    => format!("{}break;\n",    ind),
            IrStatement::Continue => format!("{}continue;\n", ind),

            IrStatement::Expr(e) => {
                match e {
                    IrExpr::PrintLn  { fmt, args } => emit_print_macro(&ind, "println", fmt, args)?,
                    IrExpr::Print    { fmt, args } => {
                        let s = emit_print_macro_str("print", fmt, args)?;
                        format!("{}{};\n{}io::stdout().flush().unwrap();\n", ind, s, ind)
                    }
                    IrExpr::EPrintLn { fmt, args } => emit_print_macro(&ind, "eprintln", fmt, args)?,
                    IrExpr::ReadLine { var }        => emit_read_line(&ind, var),
                    IrExpr::Exit(code)              =>
                        format!("{}std::process::exit({});\n", ind, ExprEmitter::emit(code)?),
                    other => format!("{}{};
", ind, ExprEmitter::emit(other)?),
                }
            }

            IrStatement::Drop(var) => format!("{}drop({});\n", ind, var),

            IrStatement::Scanf { vars: _, targets } => {
                let mut s = String::new();
                for target in targets {
                    let lhs = ExprEmitter::emit(target)?;
                    s.push_str(&format!(
                        "{ind}{{
\
                         {ind}    let mut _buf = String::new();
\
                         {ind}    io::stdin().read_line(&mut _buf)
\
                         {ind}        .expect(\"Failed to read input\");
\
                         {ind}    let _tok = _buf.split_whitespace()
\
                         {ind}        .next().unwrap_or(\"\");
\
                         {ind}    {lhs} = _tok.parse().unwrap_or_default();
\
                         {ind}}}
",
                        ind = ind, lhs = lhs
                    ));
                }
                s
            }

            IrStatement::If { condition, then_block, else_block } => {
                let mut s = format!("{}if {} {{\n", ind, ExprEmitter::emit(condition)?);
                for st in then_block { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                s.push_str(&format!("{}}}", ind));
                if let Some(eb) = else_block {
                    s.push_str(" else {\n");
                    for st in eb { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                    s.push_str(&format!("{}}}", ind));
                }
                s.push('\n');
                s
            }

            IrStatement::While { condition, body } => {
                let mut s = format!("{}while {} {{\n", ind, emit_bool_condition(condition)?);
                for st in body { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                s.push_str(&format!("{}}}\n", ind));
                s
            }

            IrStatement::While2 { init, condition, increment, body } => {
                let mut s = Self::emit_stmt(init, depth, unsafe_ctx)?;
                s.push_str(&format!("{}while {} {{\n", ind, emit_bool_condition(condition)?));
                for st in body { s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?); }
                let incr = ExprEmitter::emit(increment)?;
                if !incr.is_empty() && incr != "()" {
                    s.push_str(&format!("{}{};
", ind1, incr));
                }
                s.push_str(&format!("{}}}\n", ind));
                s
            }

            // ── match (from C switch/case) ────────────────────────────
            IrStatement::Match { expr, arms, default } => {
                let mut s = format!("{}match {} {{\n", ind, ExprEmitter::emit(expr)?);
                for (patterns, body) in arms {
                    let pat_strs: Vec<String> = patterns.iter()
                        .map(ExprEmitter::emit)
                        .collect::<anyhow::Result<_>>()?;
                    s.push_str(&format!("{}{}  => {{\n", ind1, pat_strs.join(" | ")));
                    for st in body {
                        s.push_str(&Self::emit_stmt(st, depth + 2, unsafe_ctx)?);
                    }
                    s.push_str(&format!("{}}}\n", ind1));
                }
                if let Some(def) = default {
                    s.push_str(&format!("{}_  => {{\n", ind1));
                    for st in def {
                        s.push_str(&Self::emit_stmt(st, depth + 2, unsafe_ctx)?);
                    }
                    s.push_str(&format!("{}}}\n", ind1));
                }
                s.push_str(&format!("{}}}\n", ind));
                s
            }

            // ── loop (from C do-while) ────────────────────────────────
            IrStatement::Loop { body, condition } => {
                let mut s = format!("{}loop {{\n", ind);
                for st in body {
                    s.push_str(&Self::emit_stmt(st, depth + 1, unsafe_ctx)?);
                }
                // Skip break condition for infinite loops: while(1)/while(true)/while(2)
                let is_infinite = match condition {
                    IrExpr::IntLit(n)  => *n != 0,
                    IrExpr::BoolLit(b) => *b,
                    _ => false,
                };
                if !is_infinite {
                    let cond_str = emit_bool_condition(condition)?;
                    s.push_str(&format!("{}if !({}) {{ break; }}\n", ind1, cond_str));
                }
                s.push_str(&format!("{}}}\n", ind));
                s
            }

            IrStatement::UnsafeBlock(stmts) => {
                // If we're already inside an unsafe context, skip the wrapper
                if unsafe_ctx {
                    let mut s = String::new();
                    for st in stmts { s.push_str(&Self::emit_stmt(st, depth, true)?); }
                    s
                } else {
                    let mut s = format!("{}unsafe {{\n", ind);
                    for st in stmts { s.push_str(&Self::emit_stmt(st, depth + 1, true)?); }
                    s.push_str(&format!("{}}}\n", ind));
                    s
                }
            }
        })
    }
}

// ── print macro helpers ──────────────────────────────────────────────────────

fn emit_print_macro(ind: &str, mac: &str, fmt: &str, args: &[IrExpr]) -> anyhow::Result<String> {
    Ok(format!("{}{};\n", ind, emit_print_macro_str(mac, fmt, args)?))
}

fn emit_print_macro_str(mac: &str, fmt: &str, args: &[IrExpr]) -> anyhow::Result<String> {
    if args.is_empty() {
        Ok(format!("{}!(\"{}\")", mac, fmt))
    } else {
        let args_str = args.iter()
            .map(ExprEmitter::emit)
            .collect::<anyhow::Result<Vec<_>>>()?
            .join(", ");
        Ok(format!("{}!(\"{}\", {})", mac, fmt, args_str))
    }
}

fn emit_read_line(ind: &str, var: &str) -> String {
    // Emit a typed stdin read. The variable is already declared in the
    // surrounding scope by the LetBinding for it, so we just assign here.
    // We use a fresh buffer each time to avoid borrow issues.
    format!(
        "{ind}{{\n\
         {ind}    let mut _buf = String::new();\n\
         {ind}    io::stdin().read_line(&mut _buf).expect(\"Failed to read input\");\n\
         {ind}    {var} = _buf.trim().parse().unwrap_or_default();\n\
         {ind}}}\n",
        ind = ind,
        var = var
    )
}

fn extract_array_size(rust_type: &str) -> Option<usize> {
    let semi = rust_type.find(';')?;
    let end  = rust_type.rfind(']')?;
    rust_type[semi + 1..end].trim().parse().ok()
}

// ─────────────────────────────────────────────────────────────────────────────
// Expression Emitter
// ─────────────────────────────────────────────────────────────────────────────

pub struct ExprEmitter;

impl ExprEmitter {
    pub fn emit(expr: &IrExpr) -> anyhow::Result<String> {
        Ok(match expr {
            IrExpr::IntLit(n)    => n.to_string(),
            IrExpr::FloatLit(f)  => {
                if f.fract() == 0.0 { format!("{:.1}", f) } else { f.to_string() }
            }
            IrExpr::BoolLit(b)   => b.to_string(),
            IrExpr::StringLit(s) => format!("\"{}\"", s),
            IrExpr::CharLit(c)   => format!("b'{}'", c),
            IrExpr::Null | IrExpr::NullMut => "std::ptr::null_mut()".to_string(),
            IrExpr::OptionNone   => "None".to_string(),
            IrExpr::OptionSome(i) => format!("Some({})", Self::emit(i)?),
            IrExpr::Var(name)    => name.clone(),

            IrExpr::BinOp { left, op, right } => {
                let op_prec  = binop_precedence(op);
                let left_s   = Self::emit_with_parens(left,  op_prec, false)?;
                let right_s  = Self::emit_with_parens(right, op_prec, true)?;
                format!("{} {} {}", left_s, binop_str(op), right_s)
            }

            IrExpr::UnaryOp { op, operand } =>
                format!("{}{}", unaryop_str(op), Self::emit(operand)?),

            IrExpr::Call { function, args } => {
                if function == "__to_vec__" {
                    if let Some(arr) = args.first() {
                        return Ok(format!("{}.to_vec()", Self::emit(arr)?));
                    }
                }
                // ── C stdlib sentinel translations ───────────────────────────
                // strcmp(a, b) → a.cmp(&b) as i32  (0=eq, neg=lt, pos=gt)
                if function == "__strcmp__" && args.len() == 2 {
                    return Ok(format!("{}.cmp(&{}) as i32", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }
                // strcat(dst, src) → { dst.push_str(&src); dst }
                if function == "__strcat__" && args.len() == 2 {
                    return Ok(format!("{{ {}.push_str(&{}); }}", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }
                // strcat as statement: dst.push_str(src)
                if function == "__strcat_stmt__" && args.len() == 2 {
                    let src = Self::emit(&args[1])?;
                    let src_ref = if src.starts_with('"') { src } else { format!("&{}", src) };
                    return Ok(format!("{}.push_str({})", Self::emit(&args[0])?, src_ref));
                }
                // format!(fmt, args...) — from sprintf-style assignment
                if function.starts_with("__format__:") {
                    let fmt_str = &function["__format__:".len()..];
                    let rest = args.iter().map(Self::emit)
                        .collect::<anyhow::Result<Vec<_>>>()?  .join(", ");
                    return Ok(format!("format!(\"{fmt}\", {rest})", fmt = fmt_str, rest = rest));
                }
                // memset(arr, val) → arr.fill(val)
                if function == "__memset__" && args.len() == 2 {
                    return Ok(format!("{}.fill({})", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }
                // memcpy(dst, src) → dst.copy_from_slice(&src)
                if function == "__memcpy__" && args.len() == 2 {
                    return Ok(format!("{}.copy_from_slice(&{})", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }

                // ── New string function sentinels ────────────────────────────

                // sprintf(buf, fmt, ...) → buf = format!(fmt, ...)
                // Encoded as __sprintf__:fmt_string with buf as args[0]
                if function.starts_with("__sprintf__:") {
                    let fmt_str = &function["__sprintf__:".len()..];
                    if !args.is_empty() {
                        let buf = Self::emit(&args[0])?;
                        if args.len() == 1 {
                            return Ok(
                                [buf.as_str(), " = \"", fmt_str, "\"", ".to_string()"].concat()
                            );
                        } else {
                            let rest = args[1..].iter()
                                .map(Self::emit)
                                .collect::<anyhow::Result<Vec<_>>>()?
                                .join(", ");
                            return Ok(
                                [buf.as_str(), " = format!(\"", fmt_str, "\", ", rest.as_str(), ")"].concat()
                            );
                        }
                    }
                }

                // strstr(haystack, needle) → haystack.find(needle) (returns Option<usize>)
                // We keep it simple: map to a bool-like check common in C usage
                if function == "__strstr__" && args.len() == 2 {
                    return Ok(format!("{}.find({})", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }

                // strchr(s, c) → s.find(c as char) → None/Some
                if function == "__strchr__" && args.len() == 2 {
                    return Ok(format!("{}.find({} as char)", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }
                if function == "__strrchr__" && args.len() == 2 {
                    return Ok(format!("{}.rfind({} as char)", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }

                // strtol(s, base) → i64::from_str_radix(s.trim(), base).unwrap_or(0)
                if function == "__strtol__" && args.len() == 2 {
                    return Ok(format!("i64::from_str_radix({}.trim(), {} as u32).unwrap_or(0)",
                        Self::emit(&args[0])?, Self::emit(&args[1])?));
                }

                // strtof(s) → s.trim().parse::<f32>().unwrap_or(0.0)
                if function == "__strtof__" && args.len() == 1 {
                    return Ok(format!("{}.trim().parse::<f32>().unwrap_or(0.0)", Self::emit(&args[0])?));
                }

                // strtod(s) → s.trim().parse::<f64>().unwrap_or(0.0)
                if function == "__strtod__" && args.len() == 1 {
                    return Ok(format!("{}.trim().parse::<f64>().unwrap_or(0.0)", Self::emit(&args[0])?));
                }

                // strncmp(a, b, n) → a.get(..n as usize).unwrap_or("").cmp(b.get(..n as usize).unwrap_or("")) as i32
                if function == "__strncmp__" && args.len() == 3 {
                    let a = Self::emit(&args[0])?;
                    let b = Self::emit(&args[1])?;
                    let n = Self::emit(&args[2])?;
                    return Ok(format!(
                        "{}.get(..({}) as usize).unwrap_or(\"\").cmp({}.get(..({}) as usize).unwrap_or(\"\")) as i32",
                        a, n, b, n
                    ));
                }

                // strnlen(s, max) → s.len().min(max as usize)
                if function == "__strnlen__" && args.len() == 2 {
                    return Ok(format!("{}.len().min(({}) as usize)", Self::emit(&args[0])?, Self::emit(&args[1])?));
                }

                // strtok(s, delim) — emit a note; strtok is stateful and hard to translate directly
                if function == "__strtok__" && args.len() == 2 {
                    return Ok(format!("/* strtok: use split() */ {}.split({}).next().unwrap_or(\"\")",
                        Self::emit(&args[0])?, Self::emit(&args[1])?));
                }

                // getchar() → { let mut b = [0u8;1]; std::io::stdin().read(&mut b).ok(); b[0] as i32 }
                if function == "__getchar__" {
                    return Ok("{{ let mut __b = [0u8; 1]; use std::io::Read; std::io::stdin().read_exact(&mut __b).ok(); __b[0] as i32 }}".to_string());
                }
                let args_str = args.iter()
                    .map(Self::emit)
                    .collect::<anyhow::Result<Vec<_>>>()?
                    .join(", ");
                format!("{}({})", function, args_str)
            }

            IrExpr::ArrayAccess { array, index } =>
                format!("{}[{}]", Self::emit(array)?, Self::emit(index)?),

            IrExpr::ArrayLiteral(elems) => {
                let s = elems.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                format!("[{}]", s)
            }

            IrExpr::Cast { to_type, expr } =>
                format!("({}) as {}", Self::emit(expr)?, to_type),

            IrExpr::AsUsize(inner) =>
                format!("({}) as usize", Self::emit(inner)?),

            IrExpr::BoxNew(inner)     => format!("Box::new({})", Self::emit(inner)?),
            IrExpr::RcNew(inner)      => format!("Rc::new({})", Self::emit(inner)?),
            IrExpr::RefCellNew(inner) => format!("RefCell::new({})", Self::emit(inner)?),

            IrExpr::VecNew { elem_type, len } => {
                // char/u8 arrays from C → String::with_capacity (used for char* str)
                if elem_type == "u8" || elem_type == "char" {
                    // If length is a constant, use with_capacity; otherwise new()
                    return Ok(format!("String::with_capacity({} as usize)", Self::emit(len)?));
                }
                let zero = primitive_default(elem_type);
                format!("vec![{}; {} as usize]", zero, Self::emit(len)?)
            }

            IrExpr::StructDefault(name) => format!("{}::default()", name),

            IrExpr::FieldAccess { object, field } => {
                // For C char/string function translations, the `field` may already include
                // parentheses (e.g. "is_ascii_digit()" from isdigit translation).
                // Emit as a method call in that case.
                if field.ends_with(')') {
                    format!("{}.{}", Self::emit(object)?, field)
                } else {
                    format!("{}.{}", Self::emit(object)?, field)
                }
            }

            IrExpr::StructLiteral { struct_type, fields } => {
                let mut s = format!("{} {{ ", struct_type);
                for (i, (fname, fexpr)) in fields.iter().enumerate() {
                    if i > 0 { s.push_str(", "); }
                    s.push_str(&format!("{}: {}", fname, Self::emit(fexpr)?));
                }
                s.push_str(" }");
                s
            }

            IrExpr::Deref(inner)  => format!("(*{})", Self::emit(inner)?),
            IrExpr::Ref(inner)    => format!("&{}", Self::emit(inner)?),
            IrExpr::RefMut(inner) => format!("&mut {}", Self::emit(inner)?),
            IrExpr::Clone(inner)  => format!("{}.clone()", Self::emit(inner)?),

            IrExpr::PrintLn { fmt, args } => {
                if args.is_empty() { format!("println!(\"{}\")", fmt) }
                else {
                    let a = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                    format!("println!(\"{}\", {})", fmt, a)
                }
            }
            IrExpr::Print { fmt, args } => {
                if args.is_empty() { format!("print!(\"{}\")", fmt) }
                else {
                    let a = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                    format!("print!(\"{}\", {})", fmt, a)
                }
            }
            IrExpr::EPrintLn { fmt, args } => {
                if args.is_empty() { format!("eprintln!(\"{}\")", fmt) }
                else {
                    let a = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                    format!("eprintln!(\"{}\", {})", fmt, a)
                }
            }
            IrExpr::ReadLine { var } => format!("/* read -> {} */", var),
            IrExpr::Exit(code) => format!("std::process::exit({})", Self::emit(code)?),
        })
    }
    /// Emit an expression, wrapping it in parentheses if its own precedence is
    /// lower than `parent_prec` (meaning it would bind looser than the parent
    /// operator and would be incorrectly associated without parens).
    ///
    /// `is_right` handles right-associativity: for left-associative operators
    /// (all the common arithmetic ones) the right operand needs parens even when
    /// equal precedence, because `a - (b - c) ≠ a - b - c`.
    fn emit_with_parens(expr: &IrExpr, parent_prec: u8, is_right: bool) -> anyhow::Result<String> {
        let s = Self::emit(expr)?;
        let needs_parens = match expr {
            IrExpr::BinOp { op, .. } => {
                let child_prec = binop_precedence(op);
                child_prec < parent_prec
                    || (is_right && child_prec == parent_prec
                        && !matches!(op, BinOp::Assign))
            }
            _ => false,
        };
        if needs_parens { Ok(format!("({})", s)) } else { Ok(s) }
    }
}

/// Emit a condition expression, coercing C integer booleans to Rust bool.
/// In C, `while(1)` means infinite loop and `while(0)` means never.
fn emit_bool_condition(expr: &IrExpr) -> anyhow::Result<String> {
    match expr {
        IrExpr::IntLit(0) => Ok("false".to_string()),
        IrExpr::IntLit(_) => Ok("true".to_string()),
        _ => ExprEmitter::emit(expr),
    }
}

/// Insert a lifetime annotation into a reference type string.
/// e.g. `&str` → `&'a str`, `&mut [i32]` → `&'a mut [i32]`, `&T` → `&'a T`
fn annotate_lifetime(ty: &str, lt: &str) -> String {
    if let Some(rest) = ty.strip_prefix("&mut ") {
        format!("&{} mut {}", lt, rest)
    } else if let Some(rest) = ty.strip_prefix('&') {
        format!("&{} {}", lt, rest)
    } else {
        ty.to_string()
    }
}

fn primitive_default(t: &str) -> &str {
    match t {
        "bool" => "false",
        t if t.starts_with('f') => "0.0",
        _ => "0",
    }
}

fn binop_str(op: &BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",  BinOp::Sub => "-", BinOp::Mul => "*",
        BinOp::Div => "/",  BinOp::Mod => "%",
        BinOp::Equal => "==", BinOp::NotEqual => "!=",
        BinOp::Less => "<",  BinOp::LessEq => "<=",
        BinOp::Greater => ">", BinOp::GreaterEq => ">=",
        BinOp::And => "&&", BinOp::Or => "||",
        BinOp::Assign => "=",
        BinOp::BitAnd => "&", BinOp::BitOr => "|", BinOp::BitXor => "^",
        BinOp::Shl => "<<", BinOp::Shr => ">>",
    }
}

fn unaryop_str(op: &UnaryOp) -> &'static str {
    match op {
        UnaryOp::Neg    => "-",
        UnaryOp::Not    => "!",
        UnaryOp::Deref  => "*",
        UnaryOp::AddrOf => "&",
        UnaryOp::BitNot => "!",
    }
}

/// Operator precedence — higher number = binds tighter.
/// Mirrors C/Rust precedence exactly.
fn binop_precedence(op: &BinOp) -> u8 {
    match op {
        BinOp::Assign                        => 1,
        BinOp::Or                            => 2,
        BinOp::And                           => 3,
        BinOp::BitOr                         => 4,
        BinOp::BitXor                        => 5,
        BinOp::BitAnd                        => 6,
        BinOp::Equal | BinOp::NotEqual       => 7,
        BinOp::Less  | BinOp::LessEq
            | BinOp::Greater | BinOp::GreaterEq => 8,
        BinOp::Shl   | BinOp::Shr           => 9,
        BinOp::Add   | BinOp::Sub           => 10,
        BinOp::Mul   | BinOp::Div | BinOp::Mod => 11,
    }
}

/// Wrap the body of a function in a single `unsafe { }` block.
///
/// Given code like:
/// ```text
/// pub fn foo(x: i32) -> i32 {
///     GLOBAL = x;
///     return GLOBAL;
/// }
/// ```
/// Produces:
/// ```text
/// pub fn foo(x: i32) -> i32 {
///     unsafe {
///     GLOBAL = x;
///     return GLOBAL;
///     }
/// }
/// ```
fn wrap_body_in_unsafe(fn_code: &str) -> String {
    let lines: Vec<&str> = fn_code.lines().collect();
    if lines.len() < 2 { return fn_code.to_string(); }

    // Find the opening brace of the function
    let mut open_idx = None;
    for (i, line) in lines.iter().enumerate() {
        if line.trim_end().ends_with('{') {
            open_idx = Some(i);
            break;
        }
    }
    let Some(open) = open_idx else { return fn_code.to_string(); };

    // The closing brace is the last non-empty line
    let close = lines.len() - 1;
    if lines[close].trim() != "}" { return fn_code.to_string(); }

    let mut result: Vec<String> = Vec::new();
    // Signature line(s) up to and including the opening `{`
    for line in &lines[..=open] {
        result.push(line.to_string());
    }
    // Insert `unsafe {` right after the opening brace
    result.push("    unsafe {".to_string());
    // Body lines — keep as-is (they already have 1 level of indent from FunctionTranslator)
    for line in &lines[(open + 1)..close] {
        result.push(line.to_string());
    }
    // Close the unsafe block, then the function
    result.push("    }".to_string());
    result.push("}".to_string());
    result.join("\n")
}
