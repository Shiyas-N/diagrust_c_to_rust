//! # Rust Code Generation Module (Process 0.4)
//!
//! Implements the three sub-processes of DFD Level 2 Figure 5.5:
//!   0.4.1 Function & Control Flow Translator
//!   0.4.2 Pointer & Reference Converter
//!   0.4.3 Code Assembler & Formatter
//!
//! Input:  `IrProgram` (from `ir` crate)
//! Output: Formatted Rust source code string

use ir::*;
use ast_input::{BinOp, UnaryOp};

// ─────────────────────────────────────────────────────────────────────────────
// 0.4.3 Code Assembler & Formatter
// ─────────────────────────────────────────────────────────────────────────────

pub struct CodeAssembler;

impl CodeAssembler {
    /// Generate a complete Rust source file from an `IrProgram`.
    pub fn generate(program: &IrProgram) -> anyhow::Result<String> {
        let mut out = String::new();

        // Header comment
        out.push_str("// Auto-generated by DIAGRUST\n");
        out.push_str("// Compiler-in-the-Loop C to Rust Transpiler\n\n");
        // out.push_str("// Department of Computer Applications, GEC Thrissur\n\n");

        // Required use declarations
        let mut uses = program.required_uses.clone();
        uses.sort();
        uses.dedup();
        for u in &uses {
            out.push_str(&format!("use {};\n", u));
        }
        if !uses.is_empty() {
            out.push('\n');
        }

        // Struct definitions
        for s in &program.structs {
            out.push_str("#[derive(Debug, Clone, Copy, Default)]\n");
            out.push_str(&format!("pub struct {} {{\n", s.name));
            for field in &s.fields {
                out.push_str(&format!("    pub {}: {},\n", field.name, field.rust_type));
            }
            out.push_str("}\n\n");
        }

        // Functions
        for func in &program.functions {
            out.push_str(&FunctionTranslator::emit(func)?);
            out.push_str("\n\n");
        }

        Ok(out)
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// 0.4.1 Function & Control Flow Translator
// ─────────────────────────────────────────────────────────────────────────────

pub struct FunctionTranslator;

impl FunctionTranslator {
    pub fn emit(func: &IrFunction) -> anyhow::Result<String> {
        let mut out = String::new();

        // Signature: pub fn name(params) -> ReturnType {
        out.push_str("pub fn ");
        out.push_str(&func.name);
        out.push('(');

        for (i, param) in func.parameters.iter().enumerate() {
            if i > 0 { out.push_str(", "); }
            if param.is_mutable { out.push_str("mut "); }
            out.push_str(&param.name);
            out.push_str(": ");
            out.push_str(&param.rust_type);
        }

        out.push(')');

        if func.rust_return_type != "()" {
            out.push_str(" -> ");
            out.push_str(&func.rust_return_type);
        }

        out.push_str(" {\n");

        // Body
        for stmt in &func.body {
            out.push_str(&Self::emit_stmt(stmt, 1, func.requires_unsafe)?);
        }

        out.push('}');
        Ok(out)
    }

    fn emit_stmt(stmt: &IrStatement, depth: usize, is_unsafe_ctx: bool) -> anyhow::Result<String> {
        let ind = "    ".repeat(depth);
        Ok(match stmt {
            IrStatement::LetBinding { name, rust_type, init, is_mutable } => {
                let mut_kw = if *is_mutable { "mut " } else { "" };
                let rhs = if let Some(expr) = init {
                    format!(" = {}", ExprEmitter::emit(expr)?)
                } else {
                    // Default-init arrays / primitives
                    if rust_type.starts_with('[') {
                        // Extract element type and size for zero-init
                        let zero = if rust_type.contains("f32") || rust_type.contains("f64") { "0.0" } else { "0" };
                        // Try to extract size from "[T; N]"
                        if let Some(size) = Self::extract_array_size(rust_type) {
                            format!(" = [{}; {}]", zero, size)
                        } else {
                            format!(" = [{}; 0]", zero)
                        }
                    } else {
                        String::new()
                    }
                };
                if rhs.is_empty() {
                    format!("{}let {}{}: {};\n", ind, mut_kw, name, rust_type)
                } else {
                    format!("{}let {}{}: {}{};\n", ind, mut_kw, name, rust_type, rhs)
                }
            }
            IrStatement::Assign { target, value } => {
                format!("{}{} = {};\n", ind, target, ExprEmitter::emit(value)?)
            }
            IrStatement::IndexAssign { array, index, value } => {
                format!("{}{}[{}] = {};\n", ind, array, ExprEmitter::emit(index)?, ExprEmitter::emit(value)?)
            }
            IrStatement::Return(Some(e)) => {
                format!("{}return {};\n", ind, ExprEmitter::emit(e)?)
            }
            IrStatement::Return(None) => format!("{}return;\n", ind),
            IrStatement::Break => format!("{}break;\n", ind),
            IrStatement::Continue => format!("{}continue;\n", ind),
            IrStatement::Expr(e) => format!("{}{};\n", ind, ExprEmitter::emit(e)?),
            IrStatement::If { condition, then_block, else_block } => {
                let mut s = format!("{}if {} {{\n", ind, ExprEmitter::emit(condition)?);
                for st in then_block { s.push_str(&Self::emit_stmt(st, depth + 1, is_unsafe_ctx)?); }
                s.push_str(&format!("{}}}", ind));
                if let Some(eb) = else_block {
                    s.push_str(" else {\n");
                    for st in eb { s.push_str(&Self::emit_stmt(st, depth + 1, is_unsafe_ctx)?); }
                    s.push_str(&format!("{}}}", ind));
                }
                s.push('\n');
                s
            }
            IrStatement::While { condition, body } => {
                let mut s = format!("{}while {} {{\n", ind, ExprEmitter::emit(condition)?);
                for st in body { s.push_str(&Self::emit_stmt(st, depth + 1, is_unsafe_ctx)?); }
                s.push_str(&format!("{}}}\n", ind));
                s
            }
            IrStatement::While2 { init, condition, increment, body } => {
                // Desugar: emit init, then while loop with increment at end
                let mut s = Self::emit_stmt(init, depth, is_unsafe_ctx)?;
                s.push_str(&format!("{}while {} {{\n", ind, ExprEmitter::emit(condition)?));
                for st in body { s.push_str(&Self::emit_stmt(st, depth + 1, is_unsafe_ctx)?); }
                s.push_str(&format!("{}    {};\n", ind, ExprEmitter::emit(increment)?));
                s.push_str(&format!("{}}}\n", ind));
                s
            }
            IrStatement::UnsafeBlock(stmts) => {
                let mut s = format!("{}unsafe {{\n", ind);
                for st in stmts { s.push_str(&Self::emit_stmt(st, depth + 1, true)?); }
                s.push_str(&format!("{}}}\n", ind));
                s
            }
        })
    }

    fn extract_array_size(rust_type: &str) -> Option<usize> {
        // "[T; N]" → N
        let semi = rust_type.find(';')?;
        let end = rust_type.rfind(']')?;
        rust_type[semi + 1..end].trim().parse().ok()
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// 0.4.2 Pointer & Reference Converter + expression emitter
// ─────────────────────────────────────────────────────────────────────────────

pub struct ExprEmitter;

impl ExprEmitter {
    pub fn emit(expr: &IrExpr) -> anyhow::Result<String> {
        Ok(match expr {
            IrExpr::IntLit(n)    => n.to_string(),
            IrExpr::FloatLit(f)  => {
                // Ensure Rust-parseable float literals
                if f.fract() == 0.0 { format!("{:.1}", f) } else { f.to_string() }
            }
            IrExpr::BoolLit(b)   => b.to_string(),
            IrExpr::StringLit(s) => format!("\"{}\"", s),
            IrExpr::CharLit(c)   => format!("b'{}'", c),
            IrExpr::Null | IrExpr::NullMut => "std::ptr::null_mut()".to_string(),
            IrExpr::OptionNone   => "None".to_string(),
            IrExpr::OptionSome(inner) => format!("Some({})", Self::emit(inner)?),
            IrExpr::Var(name)    => name.clone(),
            IrExpr::BinOp { left, op, right } => {
                let l = Self::emit(left)?;
                let r = Self::emit(right)?;
                let o = Self::binop_str(op);
                format!("{} {} {}", l, o, r)
            }
            IrExpr::UnaryOp { op, operand } => {
                let inner = Self::emit(operand)?;
                let o = Self::unaryop_str(op);
                format!("{}{}", o, inner)
            }
            IrExpr::Call { function, args } => {
                let args_str = args.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                format!("{}({})", function, args_str)
            }
            IrExpr::ArrayAccess { array, index } => {
                format!("{}[{}]", Self::emit(array)?, Self::emit(index)?)
            }
            IrExpr::ArrayLiteral(elems) => {
                let elems_str = elems.iter().map(Self::emit).collect::<anyhow::Result<Vec<_>>>()?.join(", ");
                format!("[{}]", elems_str)
            }
            IrExpr::Cast { to_type, expr } => {
                // Always wrap inner in parens so `as` applies to the whole expression
                // e.g. (a + b + c) as f32 — not a + b + (c as f32)
                format!("({}) as {}", Self::emit(expr)?, to_type)
            }
            IrExpr::AsUsize(inner) => {
                format!("({}) as usize", Self::emit(inner)?)
            }
            IrExpr::BoxNew(inner)     => format!("Box::new({})", Self::emit(inner)?),
            IrExpr::RcNew(inner)      => format!("Rc::new({})", Self::emit(inner)?),
            IrExpr::RefCellNew(inner) => format!("RefCell::new({})", Self::emit(inner)?),
            IrExpr::FieldAccess { object, field } => {
                format!("{}.{}", Self::emit(object)?, field)
            }
            IrExpr::StructLiteral { struct_type, fields } => {
                let mut s = format!("{} {{ ", struct_type);
                for (i, (fname, fexpr)) in fields.iter().enumerate() {
                    if i > 0 { s.push_str(", "); }
                    s.push_str(&format!("{}: {}", fname, Self::emit(fexpr)?));
                }
                s.push_str(" }");
                s
            }
        })
    }

    fn binop_str(op: &BinOp) -> &'static str {
        match op {
            BinOp::Add    => "+",
            BinOp::Sub    => "-",
            BinOp::Mul    => "*",
            BinOp::Div    => "/",
            BinOp::Mod    => "%",
            BinOp::Equal  => "==",
            BinOp::NotEqual => "!=",
            BinOp::Less   => "<",
            BinOp::LessEq => "<=",
            BinOp::Greater => ">",
            BinOp::GreaterEq => ">=",
            BinOp::And    => "&&",
            BinOp::Or     => "||",
            BinOp::Assign => "=",
            BinOp::BitAnd => "&",
            BinOp::BitOr  => "|",
            BinOp::BitXor => "^",
            BinOp::Shl    => "<<",
            BinOp::Shr    => ">>",
        }
    }

    fn unaryop_str(op: &UnaryOp) -> &'static str {
        match op {
            UnaryOp::Neg   => "-",
            UnaryOp::Not   => "!",
            UnaryOp::Deref => "*",
            UnaryOp::AddrOf => "&",
            UnaryOp::BitNot => "!",  // Rust uses ! for bitwise not on integers
        }
    }
}
