//! # Rust Code Generation Module

use ir::*;
use ast_input::{BinOp, UnaryOp};

pub struct CodeAssembler;

impl CodeAssembler {
    pub fn generate(program: &IrProgram) -> anyhow::Result<String> {
        let mut out = String::new();

        out.push_str("// Auto-generated by DIAGRUST\n");
        out.push_str("// Compiler-in-the-Loop C to Rust Transpiler\n\n");

        let mut uses = program.required_uses.clone();
        if program.is_executable {
            uses.push("std::io::{self, Write}".to_string());
        }
        uses.sort();
        uses.dedup();
        for u in &uses {
            out.push_str(&format!("use {};\n", u));
        }
        if !uses.is_empty() { out.push('\n'); }

        // Struct definitions
        for s in &program.structs {
            let all_copy = s.fields.iter().all(|f| is_copy_type(&f.rust_type));
            let needs_manual = s.fields.iter().any(|f| needs_manual_default_impl(&f.rust_type));
            if all_copy && !needs_manual {
                out.push_str("#[derive(Debug, Clone, Copy, Default)]\n");
            } else if !needs_manual {
                out.push_str("#[derive(Debug, Clone, Default)]\n");
            } else if all_copy {
                out.push_str("#[derive(Debug, Clone, Copy)]\n");
            } else {
                out.push_str("#[derive(Debug, Clone)]\n");
            }
            out.push_str(&format!("pub struct {} {{\n", s.name));
            for field in &s.fields {
                out.push_str(&format!("    pub {}: {},\n", field.name, field.rust_type));
            }
            out.push_str("}\n");
            if needs_manual {
                out.push_str(&format!("impl Default for {} {{\n    fn default() -> Self {{\n        Self {{\n", s.name));
                for field in &s.fields {
                    let def_val = field_default_value(&field.rust_type, &field.name);
                    out.push_str(&format!("            {},\n", def_val));
                }
                out.push_str("        }\n    }\n}\n");
            }
            out.push('\n');
        }

        // Global variables / constants
        for gv in &program.global_vars {
            if gv.is_const {
                if let Some(init) = &gv.init {
                    out.push_str(&format!("pub const {}: {} = {};\n",
                        gv.name.to_uppercase(), gv.rust_type, ExprEmitter::emit(init)?));
                }
            } else {
                let init_str = static_init_for_type(&gv.rust_type, gv.init.as_ref());
                out.push_str(&format!(
                    "// Global variable — use unsafe {{ }} to access\nstatic mut {}: {} = {};\n",
                    gv.name.to_uppercase(), gv.rust_type, init_str
                ));
            }
        }
        if !program.global_vars.is_empty() { out.push('\n'); }

        // Functions
        for func in &program.functions {
            out.push_str(&FunctionTranslator::emit(func)?);
            out.push_str("\n\n");
        }

        Ok(out)
    }
}

fn is_copy_type(t: &str) -> bool {
    matches!(t, "i8"|"i16"|"i32"|"i64"|"i128"|"isize"
               |"u8"|"u16"|"u32"|"u64"|"u128"|"usize"
               |"f32"|"f64"|"bool"|"char"|"()")
    || t.starts_with('*')
    || (t.starts_with('[') && t.contains(';'))
}

fn needs_manual_default_impl(t: &str) -> bool {
    if !t.starts_with('[') { return false; }
    if let Some(sz) = extract_array_size(t) { sz > 32 } else { false }
}

fn extract_array_elem_type(t: &str) -> String {
    if let (Some(start), Some(semi)) = (t.find('['), t.find(';')) {
        t[start + 1..semi].trim().to_string()
    } else { "i32".to_string() }
}

fn array_default_value(elem_type: &str) -> String {
    match elem_type {
        "f32" | "f64" => "0.0".to_string(),
        "bool" => "false".to_string(),
        t if t.starts_with('*') => "std::ptr::null_mut()".to_string(),
        "i8"|"i16"|"i32"|"i64"|"i128"|"isize"
        |"u8"|"u16"|"u32"|"u64"|"u128"|"usize" => "0".to_string(),
        other => format!("{} {{ ..Default::default() }}", other),
    }
}

fn static_init_for_type(rust_type: &str, _init: Option<&IrExpr>) -> String {
    if rust_type.starts_with('[') {
        if let Some(sz) = extract_array_size(rust_type) {
            let elem = extract_array_elem_type(rust_type);
            if elem.chars().next().map(|c| c.is_uppercase()).unwrap_or(false) {
                return "unsafe { std::mem::zeroed() }".to_string();
            }
            let zero = match elem.as_str() {
                "f32" | "f64" => "0.0", "bool" => "false", _ => "0",
            };
            return format!("[{}; {}]", zero, sz);
        }
    }
    match rust_type {
        "i32"|"u32"|"i64"|"u64"|"i16"|"u16"|"i8"|"u8"|"usize"|"isize" => "0".to_string(),
        "f32"|"f64" => "0.0".to_string(),
        "bool" => "false".to_string(),
        _ => "0".to_string(),
    }
}

fn field_default_value(rust_type: &str, field_name: &str) -> String {
    if rust_type.starts_with('[') {
        if let Some(sz) = extract_array_size(rust_type) {
            let elem = extract_array_elem_type(rust_type);
            let zero = match elem.as_str() { "f32" | "f64" => "0.0", "bool" => "false", _ => "0" };
            return format!("{}: [{}; {}]", field_name, zero, sz);
        }
    }
    let def = match rust_type {
        "f32" | "f64" => "0.0".to_string(),
        "bool" => "false".to_string(),
        t if t.starts_with('*') => "std::ptr::null_mut()".to_string(),
        _ if rust_type.chars().next().map(|c| c.is_uppercase()).unwrap_or(false) =>
            format!("{}::default()", rust_type),
        _ => "0".to_string(),
    };
    format!("{}: {}", field_name, def)
}

