use anyhow::Result;
use ast_input::*;

/// Translates C AST to Rust code
pub struct RustTranslator {
    unsafe_mode: bool,
}

impl RustTranslator {
    pub fn new(unsafe_mode: bool) -> Self {
        Self { unsafe_mode }
    }
    
    pub fn translate(&self, program: &CProgram) -> Result<String> {
        let mut output = String::new();
        
        // Add standard header
        output.push_str("// Auto-generated by DIAGRUST\n");
        output.push_str("// C to Rust Transpiler - MVP\n\n");
        
        // Translate each function
        for function in &program.functions {
            let rust_fn = self.translate_function(function)?;
            output.push_str(&rust_fn);
            output.push_str("\n\n");
        }
        
        Ok(output)
    }
    
    fn translate_function(&self, function: &CFunction) -> Result<String> {
        let mut output = String::new();
        
        // Function signature
        output.push_str("pub fn ");
        output.push_str(&function.name);
        output.push('(');
        
        // Parameters
        for (i, param) in function.parameters.iter().enumerate() {
            if i > 0 {
                output.push_str(", ");
            }
            output.push_str(&param.name);
            output.push_str(": ");
            output.push_str(&self.translate_type(&param.param_type));
        }
        
        output.push(')');
        
        // Return type
        let return_type = self.translate_type(&function.return_type);
        if return_type != "()" {
            output.push_str(" -> ");
            output.push_str(&return_type);
        }
        
        // Function body
        output.push_str(" {\n");
        
        for stmt in &function.body {
            let rust_stmt = self.translate_statement(stmt, 1)?;
            output.push_str(&rust_stmt);
        }
        
        output.push('}');
        
        Ok(output)
    }
    
    fn translate_type(&self, ctype: &CType) -> String {
        match ctype {
            CType::Void => "()".to_string(),
            CType::Int => "i32".to_string(),
            CType::Char => "u8".to_string(),
            CType::Float => "f32".to_string(),
            CType::Double => "f64".to_string(),
            CType::Pointer(inner) => {
                if self.unsafe_mode {
                    format!("*mut {}", self.translate_type(inner))
                } else {
                    // Try to use safe references in MVP
                    format!("&mut {}", self.translate_type(inner))
                }
            }
            CType::Unknown(name) => name.clone(),
        }
    }
    
    fn translate_statement(&self, stmt: &CStatement, indent: usize) -> Result<String> {
        let indent_str = "    ".repeat(indent);
        
        match stmt {
            CStatement::Return(Some(expr)) => {
                let rust_expr = self.translate_expression(expr)?;
                Ok(format!("{}return {};\n", indent_str, rust_expr))
            }
            CStatement::Return(None) => {
                Ok(format!("{}return;\n", indent_str))
            }
            CStatement::VarDecl { name, var_type, init } => {
                let rust_type = self.translate_type(var_type);
                if let Some(init_expr) = init {
                    let rust_expr = self.translate_expression(init_expr)?;
                    Ok(format!("{}let {}: {} = {};\n", indent_str, name, rust_type, rust_expr))
                } else {
                    Ok(format!("{}let {}: {};\n", indent_str, name, rust_type))
                }
            }
            CStatement::Assignment { target, value } => {
                let rust_expr = self.translate_expression(value)?;
                Ok(format!("{}{} = {};\n", indent_str, target, rust_expr))
            }
            CStatement::Expression(expr) => {
                let rust_expr = self.translate_expression(expr)?;
                Ok(format!("{}{};\n", indent_str, rust_expr))
            }
            CStatement::If { condition, then_body, else_body } => {
                let mut output = String::new();
                let cond = self.translate_expression(condition)?;
                output.push_str(&format!("{}if {} {{\n", indent_str, cond));
                
                for stmt in then_body {
                    output.push_str(&self.translate_statement(stmt, indent + 1)?);
                }
                
                output.push_str(&format!("{}}}", indent_str));
                
                if let Some(else_stmts) = else_body {
                    output.push_str(" else {\n");
                    for stmt in else_stmts {
                        output.push_str(&self.translate_statement(stmt, indent + 1)?);
                    }
                    output.push_str(&format!("{}}}", indent_str));
                }
                
                output.push('\n');
                Ok(output)
            }
            CStatement::While { condition, body } => {
                let mut output = String::new();
                let cond = self.translate_expression(condition)?;
                output.push_str(&format!("{}while {} {{\n", indent_str, cond));
                
                for stmt in body {
                    output.push_str(&self.translate_statement(stmt, indent + 1)?);
                }
                
                output.push_str(&format!("{}}}\n", indent_str));
                Ok(output)
            }
            CStatement::For { init, condition, increment, body } => {
                let mut output = String::new();
                
                // Check if this is a simple range-based for loop (i = 0; i < n; i++)
                if Self::is_simple_range_loop(init, condition, increment) {
                    // Extract variable name and range
                    if let CStatement::VarDecl { name, .. } = init.as_ref() {
                        if let CExpression::BinaryOp { left: _, op: BinOp::Less, right } = condition {
                            // Generate idiomatic Rust: for i in 0..n
                            let range_end = self.translate_expression(right)?;
                            output.push_str(&format!("{}for {} in 0..{} {{\n", indent_str, name, range_end));
                            
                            for stmt in body {
                                output.push_str(&self.translate_statement(stmt, indent + 1)?);
                            }
                            
                            output.push_str(&format!("{}}}\n", indent_str));
                            return Ok(output);
                        }
                    }
                }
                
                // Fallback: convert to while loop
                // Translate init
                output.push_str(&self.translate_statement(init, indent)?);
                
                // While condition
                let cond = self.translate_expression(condition)?;
                output.push_str(&format!("{}while {} {{\n", indent_str, cond));
                
                // Body
                for stmt in body {
                    output.push_str(&self.translate_statement(stmt, indent + 1)?);
                }
                
                // Increment at end
                let incr = self.translate_expression(increment)?;
                output.push_str(&format!("{}    {};\n", indent_str, incr));
                
                output.push_str(&format!("{}}}\n", indent_str));
                Ok(output)
            }
        }
    }
    
    fn translate_expression(&self, expr: &CExpression) -> Result<String> {
        match expr {
            CExpression::Literal(lit) => Ok(self.translate_literal(lit)),
            CExpression::Variable(name) => Ok(name.clone()),
            CExpression::BinaryOp { left, op, right } => {
                let left_str = self.translate_expression(left)?;
                let right_str = self.translate_expression(right)?;
                let op_str = self.translate_binop(op);
                Ok(format!("{} {} {}", left_str, op_str, right_str))
            }
            CExpression::UnaryOp { op, operand } => {
                let operand_str = self.translate_expression(operand)?;
                let op_str = self.translate_unaryop(op);
                Ok(format!("{}{}", op_str, operand_str))
            }
            CExpression::Call { function, args } => {
                let args_results: Result<Vec<String>> = args
                    .iter()
                    .map(|a| self.translate_expression(a))
                    .collect();
                let args_str = args_results?.join(", ");
                Ok(format!("{}({})", function, args_str))
            }
            CExpression::Null => Ok("std::ptr::null_mut()".to_string()),
        }
    }
    
    fn translate_literal(&self, lit: &CLiteral) -> String {
        match lit {
            CLiteral::Int(n) => n.to_string(),
            CLiteral::Float(f) => f.to_string(),
            CLiteral::String(s) => format!("\"{}\"", s),
            CLiteral::Char(c) => format!("'{}'", c),
        }
    }
    
    fn translate_binop(&self, op: &BinOp) -> &str {
        match op {
            BinOp::Add => "+",
            BinOp::Sub => "-",
            BinOp::Mul => "*",
            BinOp::Div => "/",
            BinOp::Mod => "%",
            BinOp::Equal => "==",
            BinOp::NotEqual => "!=",
            BinOp::Less => "<",
            BinOp::LessEq => "<=",
            BinOp::Greater => ">",
            BinOp::GreaterEq => ">=",
            BinOp::And => "&&",
            BinOp::Or => "||",
            BinOp::Assign => "=",
        }
    }
    
    fn translate_unaryop(&self, op: &UnaryOp) -> &str {
        match op {
            UnaryOp::Neg => "-",
            UnaryOp::Not => "!",
            UnaryOp::Deref => "*",
            UnaryOp::AddrOf => "&",
        }
    }
    
    // Helper to detect simple range-based for loops
    fn is_simple_range_loop(init: &CStatement, condition: &CExpression, increment: &CExpression) -> bool {
        // Check init: int i = 0
        if let CStatement::VarDecl { init: Some(init_expr), .. } = init {
            if let CExpression::Literal(CLiteral::Int(0)) = init_expr {
                // Check condition: i < n
                if let CExpression::BinaryOp { op: BinOp::Less, .. } = condition {
                    // Check increment: i++ or i = i + 1
                    if let CExpression::BinaryOp { op: BinOp::Add, right, .. } = increment {
                        if let CExpression::Literal(CLiteral::Int(1)) = right.as_ref() {
                            return true;
                        }
                    }
                }
            }
        }
        false
    }
}

/// Helper to format Rust code (basic)
pub fn format_rust_code(code: &str) -> String {
    // MVP: Just ensure consistent spacing
    code.lines()
        .map(|line| line.trim_end())
        .collect::<Vec<_>>()
        .join("\n")
}